import { Context, Service } from 'cordis'
import fs from 'node:fs/promises'
import path from 'node:path'

export interface SpecDocument {
  title: string
  objective: string
  schemaChanges?: string
  affectedFiles: string[]
  validationPlan: string
  breakingChangesRisk?: 'none' | 'low' | 'medium' | 'high'
  mitigationStrategy?: string
}

export interface SpecValidationResult {
  approved: boolean
  critiqueNotes: string[]
  formattedMarkdown: string
}

declare module 'cordis' {
  interface Context {
    a3hSpecGate: SpecGateService
  }
}

export class SpecGateService extends Service {
  constructor(ctx: Context) {
    super(ctx, 'a3hSpecGate', true)
  }

  formatSpec(doc: SpecDocument): string {
    const lines: string[] = [
      `# Architecture RFC & Implementation Specification: ${doc.title}`,
      '',
      '> Generated by A3H Supervisor. Verified by Critic Gate before worktree allocation.',
      '',
      '## 1. Objective',
      doc.objective || '(none specified)',
      '',
      '## 2. Affected File Manifest',
      ...(doc.affectedFiles && doc.affectedFiles.length > 0
        ? doc.affectedFiles.map(f => `- \`${f}\``)
        : ['- *None specified*']),
      '',
      '## 3. Schema & Interface Changes',
      doc.schemaChanges || '- *No database or schema alterations required.*',
      '',
      '## 4. Test Validation Plan',
      doc.validationPlan || '- *No validation plan specified.*',
      '',
      '## 5. Risk Assessment & Invariant Protection',
      `- **Breaking Change Risk**: \`${doc.breakingChangesRisk || 'low'}\``,
    ]

    if (doc.mitigationStrategy) {
      lines.push(`- **Mitigation Strategy**: ${doc.mitigationStrategy}`)
    }

    return lines.join('\n')
  }

  validateSpec(doc: SpecDocument): SpecValidationResult {
    const critiqueNotes: string[] = []

    if (!doc.title || doc.title.trim().length < 5) {
      critiqueNotes.push('CRITIQUE: Specification title must be at least 5 characters long.')
    }

    if (!doc.objective || doc.objective.trim().length < 10) {
      critiqueNotes.push('CRITIQUE: Specification must articulate a clear objective (minimum 10 characters).')
    }

    if (!doc.affectedFiles || doc.affectedFiles.length === 0) {
      critiqueNotes.push('CRITIQUE: Specification must identify at least one affected file.')
    }

    if (!doc.validationPlan || doc.validationPlan.trim().length < 15) {
      critiqueNotes.push('CRITIQUE: Specification must include a concrete, verifiable test validation plan.')
    }

    if (doc.breakingChangesRisk === 'high' && !doc.mitigationStrategy) {
      critiqueNotes.push('CRITIQUE: High-risk breaking changes require an explicit mitigationStrategy.')
    }

    const approved = critiqueNotes.length === 0
    const formattedMarkdown = this.formatSpec(doc)

    return {
      approved,
      critiqueNotes,
      formattedMarkdown,
    }
  }

  async saveSpecArtifact(repoRoot: string, doc: SpecDocument): Promise<string> {
    const agentDir = path.resolve(repoRoot, '.agent')
    await fs.mkdir(agentDir, { recursive: true })
    const specPath = path.resolve(agentDir, 'SPEC.md')
    const content = this.formatSpec(doc)
    await fs.writeFile(specPath, content, 'utf8')
    return specPath
  }
}
